# 1. Tạo một danh sách các số
danh_sach_so = [10, 20, 30, 40, 50]

# 2. Tính tổng các số trong danh sách
tong = sum(danh_sach_so)

# 3. Đếm xem có bao nhiêu số trong danh sách
so_luong = len(danh_sach_so)

# 4. Tính trung bình
giatri_trungbinh = tong / so_luong

# 5. In kết quả
print("Danh sách số của bạn là:", danh_sach_so)
print(f"Giá trị trung bình của dãy số là: {giatri_trungbinh}")

